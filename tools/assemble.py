#!/usr/bin/env python3
"""Assemble Gmarc's Gen 2 QoL Mod from its source mods.

The generated tree is committed to this repository on purpose: the files that
ship are readable, diffable and blameable here.  Sources stay authoritative in
their own repositories; this script only copies them.

usage:
    python3 tools/assemble.py            # regenerate the tree in place
    python3 tools/assemble.py --check    # fail if the tree is stale
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT / "sources.json"
# Source mods are never committed here.  Point this at a directory that holds
# the twelve checkouts, laid out as sources.json says, with --sources-root or
# PACK_SOURCES_ROOT, or clone them into ./sources.
DEFAULT_SOURCES_ROOT = ROOT / "sources"

# Source-only material: tests, docs, git metadata and caches never ship.
# Mirrors scripts/export-mods.py EXCLUDED_DIRS: anything it strips can never
# ship, so vendoring it here would only add weight to every rebuild.
SKIP_DIRS = {".git", ".github", "tests", "docs", "tools", "__pycache__",
             ".idea", "dist", "roms", "baseroms", "model_extract",
             "translations", "painter_out", "review"}
# Mod-level metadata belongs to the standalone product, not to a vendored copy:
# a nested manifest.json still carries a github field, and the pack must not
# point anywhere.  Licences and notices stay, because attribution needs them.
SKIP_FILES = {".gitignore", ".gitattributes",
              "manifest.json", "meta.json", "mod.card",
              "README.md", "CHANGELOG.md", "CONTEST.md", "PLAN.md"}

GENERATED_HEADER = (
    "-- GENERATED by tools/assemble.py from sources.json.\n"
    "-- Do not edit: change the source mod or sources.json and reassemble.\n"
)


def load_config() -> dict:
    with CONFIG.open(encoding="utf-8") as handle:
        return json.load(handle)


def source_digest(source: Path, files: list[Path]) -> str:
    digest = hashlib.sha256()
    for path in files:
        rel = path.relative_to(source).as_posix()
        digest.update(rel.encode("utf-8"))
        digest.update(b"\0")
        digest.update(path.read_bytes())
        digest.update(b"\0")
    return digest.hexdigest()


def collect(source: Path, exclude: list[str] | None = None) -> list[Path]:
    """Every shippable file, following directory symlinks.

    free-fly and wild-skies link lib/shared at the shared sky-common library.
    The pack materializes those links so it ships one self-contained tree; the
    copies come from the same source and --check keeps them in step.
    """
    excluded = [Path(item) for item in (exclude or [])]
    out: list[Path] = []
    for dirpath, dirnames, filenames in os.walk(source, followlinks=True):
        base = Path(dirpath)
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
        for name in sorted(filenames):
            path = base / name
            rel = path.relative_to(source)
            if name in SKIP_FILES:
                continue
            if path.suffix.lower() in {".zip", ".modpkg"}:
                continue
            if any(rel == item or item in rel.parents for item in excluded):
                continue
            if not path.exists():
                continue
            out.append(path)
    return out


def apply_patch(text: str, patch: dict, product_id: str, label: str) -> str:
    find = patch["find"]
    replace = patch["replace"].replace("{product}", product_id)
    count = text.count(find)
    if count != 1:
        raise SystemExit(
            f"{label}: patch target appears {count} times, expected once:\n  {find}"
        )
    return text.replace(find, replace)


def git_commit(source: Path) -> str | None:
    try:
        out = subprocess.run(
            ["git", "-C", str(source), "rev-parse", "--short=12", "HEAD"],
            capture_output=True, text=True, check=True,
        )
        return out.stdout.strip() or None
    except (subprocess.CalledProcessError, FileNotFoundError):
        return None


def lua_string(value: str) -> str:
    """A Lua short string. JSON's \\u escapes are not Lua, so escape by hand."""
    out = value.replace(chr(92), chr(92) + chr(92))
    out = out.replace('"', chr(92) + '"')
    out = out.replace(chr(10), chr(92) + "n")
    out = out.replace(chr(13), chr(92) + "r")
    out = out.replace(chr(9), chr(92) + "t")
    return '"' + out + '"'


def lua_options(overrides: dict | None) -> str:
    """Render per-row label/help overrides as a Lua table literal."""
    if not overrides:
        return "nil"
    parts = []
    for key in sorted(overrides):
        spec = overrides[key]
        fields = []
        if spec.get("label"):
            fields.append("label=" + lua_string(spec["label"]))
        if spec.get("help"):
            fields.append("help=" + lua_string(spec["help"]))
        parts.append("[%s]={%s}" % (lua_string(key), ",".join(fields)))
    return "{" + ",".join(parts) + "}"


def render_main(config: dict, manifest: dict, features: list[dict]) -> str:
    product_id = config["product"]["id"]
    rows = []
    for feature in features:
        rows.append(
            "  { name = %s, source = %s, version = %s, options = %s },"
            % (
                lua_string(feature["name"]),
                lua_string(feature["source"]),
                lua_string(feature["version"]),
                lua_options(feature.get("options")),
            )
        )
    table = "\n".join(rows)
    return f"""{GENERATED_HEADER}
-- {manifest["name"]} {manifest["version"]} ({product_id})
--
-- Each feature keeps its own entry chunk from its source mod.  A per-feature
-- proxy gives it a private view of `mod`:
--   * `mod.path` / `mod:read` resolve inside features/<name>/
--   * option keys are namespaced as "<feature>.<key>" so eight schemas cannot
--     collide in one options screen
--   * `mod.exports` is captured per feature and merged afterwards, because
--     several sources replace the table wholesale
-- Feature order is the ascending priority the standalone mods used.

local PRODUCT = {lua_string(product_id)}

local FEATURES = {{
{table}
}}

local function featureApi(mod, feature, combined)
  local root = "features/" .. feature.name
  local state = {{ exports = {{}} }}

  local function prefixed(key)
    return feature.name .. "." .. tostring(key)
  end

  -- mod.options:define REPLACES the mod's schema, so every feature after the
  -- first would wipe the previous feature's toggles off the options screen.
  -- Keep one accumulated table and hand the engine the same object every time.
  -- mod.assets:path/image close over the real mod root, so without this every
  -- feature would look for its art in features/<name>/ nowhere: the pack root.
  local assets = setmetatable({{}}, {{ __index = mod.assets }})
  function assets:path(relative)
    return mod.assets:path(root .. "/" .. tostring(relative))
  end
  function assets:image(relative)
    return mod.assets:image(root .. "/" .. tostring(relative))
  end
  function assets:list(relative)
    if relative == nil then return mod.assets:list(root) end
    return mod.assets:list(root .. "/" .. tostring(relative))
  end
  function assets:info(relative)
    return mod.assets:info(root .. "/" .. tostring(relative))
  end

  local options = {{
    define = function(_, schema)
      for _, row in ipairs(schema) do
        local copy = {{}}
        for key, value in pairs(row) do copy[key] = value end
        copy.key = prefixed(row.key)
        local override = feature.options and feature.options[row.key]
        if override then
          if override.label then copy.label = override.label end
          if override.help then copy.help = override.help end
        end
        combined[#combined + 1] = copy
      end
      return mod.options:define(combined)
    end,
    get = function(_, key)
      return mod.options:get(prefixed(key))
    end,
  }}

  local proxy = setmetatable({{}}, {{
    __index = function(_, key)
      if key == "path" then return mod.path .. "/" .. root end
      if key == "options" then return options end
      if key == "assets" then return assets end
      if key == "exports" then return state.exports end
      return mod[key]
    end,
    __newindex = function(_, key, value)
      if key == "exports" then state.exports = value return end
      mod[key] = value
    end,
  }})

  return proxy, state
end

return function(mod)
  local merged = mod.exports
  -- Shared across every feature: define() replaces the engine's schema, so the
  -- accumulated table is what keeps all twelve option screens alive.
  local combined = {{}}
  for _, feature in ipairs(FEATURES) do
    local source = assert(mod:read("features/" .. feature.name .. "/main.lua"),
      "missing feature entry: " .. feature.name)
    local chunk = assert(loadstring(source, "@" .. PRODUCT .. "/" .. feature.name))
    local proxy, state = featureApi(mod, feature, combined)
    -- Sources use one of two entry styles: `local mod = ...` executed at load
    -- time, or `return function(mod) ... end`.  Both get the same proxy.
    local install = chunk(proxy)
    if type(install) == "function" then install(proxy) end
    for key, value in pairs(state.exports) do
      -- The same shared helper (sky-common) exports the same function from
      -- two features; that is not a collision worth reporting.
      if merged[key] ~= nil and merged[key] ~= value then
        mod.log:warn("export %q from %s replaces an earlier one",
          tostring(key), feature.name)
      end
      merged[key] = value
    end
  end
end
"""


def build(dest: Path, config: dict, sources_root: Path) -> list[str]:
    product = config["product"]
    product_id = product["id"]
    manifest_path = ROOT / "manifest.json"
    with manifest_path.open(encoding="utf-8") as handle:
        manifest = json.load(handle)
    if manifest.get("id") != product_id:
        raise SystemExit(
            f"manifest id {manifest.get('id')!r} does not match sources.json "
            f"product id {product_id!r}")
    if manifest.get("version") != product.get("version"):
        raise SystemExit(
            f"manifest version {manifest.get('version')!r} does not match "
            f"sources.json version {product.get('version')!r}; bump both")

    features_out = []
    for feature in config["features"]:
        source = (sources_root / feature["source"]).resolve()
        if not source.is_dir():
            raise SystemExit(
                f"missing source mod {feature['source']!r} under {sources_root}; "
                "clone it there, pass --sources-root, or set PACK_SOURCES_ROOT")
        files = collect(source, feature.get("exclude"))
        if not files:
            raise SystemExit(f"source has no shippable files: {feature['path']}")

        target = dest / "features" / feature["name"]
        for path in files:
            rel = path.relative_to(source)
            data = path.read_bytes()
            if rel.as_posix() in {p["file"] for p in feature.get("patches", [])}:
                text = apply_patch(
                    data.decode("utf-8"), 
                    next(p for p in feature["patches"] if p["file"] == rel.as_posix()),
                    product_id,
                    f"{feature['name']}/{rel}",
                )
                data = text.encode("utf-8")
            out = target / rel
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_bytes(data)

        version = "0.0.0"
        source_manifest = source / "manifest.json"
        if source_manifest.is_file():
            with source_manifest.open(encoding="utf-8") as handle:
                version = json.load(handle).get("version", version)

        features_out.append({
            "name": feature["name"],
            "source": feature["source"],
            "version": version,
            "options": feature.get("option_labels"),
            "priority": feature.get("priority"),
            "commit": git_commit(source),
            "digest": source_digest(source, files),
        })

    features_out.sort(key=lambda row: (row["priority"] if row["priority"] is not None else 0,
                                      row["name"]))

    (dest / "main.lua").write_text(
        render_main(config, manifest, features_out), encoding="utf-8")

    sources_doc = {
        "product": product,
        "generated_by": "tools/assemble.py",
        "features": features_out,
    }
    (dest / "SOURCES.json").write_text(
        json.dumps(sources_doc, indent=2, sort_keys=False) + "\n", encoding="utf-8")

    return [row["name"] for row in features_out]


def tree_files(root: Path) -> list[str]:
    out = []
    for path in sorted(root.rglob("*")):
        if path.is_dir():
            continue
        rel = path.relative_to(root)
        if len(rel.parts) > 1 and rel.parts[0] == "features":
            out.append(rel.as_posix())
        elif rel.as_posix() in {"main.lua", "SOURCES.json"}:
            out.append(rel.as_posix())
    return out


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true",
                        help="verify the committed tree matches the sources")
    parser.add_argument("--sources-root", type=Path,
                        default=None,
                        help="directory holding the source mods "
                             "(default: $PACK_SOURCES_ROOT or ./sources)")
    args = parser.parse_args()
    config = load_config()
    sources_root = (args.sources_root
                    or Path(os.environ.get("PACK_SOURCES_ROOT", DEFAULT_SOURCES_ROOT))
                    ).resolve()

    if not args.check:
        shutil.rmtree(ROOT / "features", ignore_errors=True)
        names = build(ROOT, config, sources_root)
        print(f"assembled {len(names)} features from {sources_root}")
        for name in names:
            print(f"  - {name}")
        return 0

    with tempfile.TemporaryDirectory() as tmp:
        staging = Path(tmp)
        build(staging, config, sources_root)
        expected = tree_files(staging)
        actual = tree_files(ROOT)
        stale = False
        if expected != actual:
            only_expected = sorted(set(expected) - set(actual))
            only_actual = sorted(set(actual) - set(expected))
            for rel in only_expected:
                print(f"missing: {rel}")
            for rel in only_actual:
                print(f"unexpected: {rel}")
            stale = True
        for rel in expected:
            if rel in actual and (staging / rel).read_bytes() != (ROOT / rel).read_bytes():
                print(f"out of date: {rel}")
                stale = True
    if stale:
        print("tree is stale; run python3 tools/assemble.py")
        return 1
    print("tree matches the sources")
    return 0


if __name__ == "__main__":
    sys.exit(main())
